#!/usr/bin/env node
// Data-integrity check. Run by `npm run check` and before every production build.
//
// 1. Finds every "PLACEHOLDER" and "TODO: confirm" in src/content and src/data,
//    and rewrites PLACEHOLDERS.md from them.
// 2. Every publication DOI must have a stored Crossref record whose title matches.
// 3. No publication may claim "published".
//
// Exits 1 if anything fails. `--allow-placeholders` reports placeholders without
// failing (dev and preview builds only).

import { fileURLToPath } from 'node:url';
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const allowPlaceholders = process.argv.includes('--allow-placeholders');
const SCAN_DIRS = ['src/content', 'src/data'];
const MARKERS = /PLACEHOLDER|TODO: confirm/;

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return walk(p);
    return /\.(json|md|mdx|ya?ml)$/.test(name) ? [p] : [];
  });
}

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const errors = [];

// 1. Placeholders
const hits = [];
for (const dir of SCAN_DIRS) {
  for (const file of walk(join(root, dir))) {
    readFileSync(file, 'utf8')
      .split(/\r?\n/)
      .forEach((line, i) => {
        if (MARKERS.test(line)) {
          hits.push({ file: relative(root, file).replaceAll('\\', '/'), line: i + 1, text: line.trim() });
        }
      });
  }
}

const md = [
  '# Placeholders',
  '',
  'Generated by `npm run check`. Do not edit by hand. A production build fails while this list is non-empty.',
  '',
  hits.length ? `${hits.length} open item(s).` : 'None. Production build allowed.',
  '',
  ...hits.map((h) => `- [${h.file}:${h.line}](${h.file}#L${h.line}) \`${h.text.slice(0, 160).replaceAll('`', "'")}\``),
  '',
].join('\n');
writeFileSync(join(root, 'PLACEHOLDERS.md'), md);

if (hits.length && !allowPlaceholders) {
  errors.push(`${hits.length} placeholder(s) remain. See PLACEHOLDERS.md.`);
}

// 2 and 3. Publications
const pubDir = join(root, 'src/content/publications');
for (const file of walk(pubDir)) {
  if (!file.endsWith('.json')) continue;
  const name = relative(root, file);
  const pub = JSON.parse(readFileSync(file, 'utf8'));

  if (/^published$/i.test(pub.status ?? '')) {
    errors.push(`${name}: status "published" is not allowed.`);
  }

  if (pub.doi) {
    const path = join(root, 'src/data/crossref', `${pub.doi.toLowerCase().replaceAll('/', '_')}.json`);
    if (!existsSync(path)) {
      errors.push(`${name}: DOI ${pub.doi} has no Crossref record. Run: npm run verify-doi -- ${pub.doi}`);
      continue;
    }
    const rec = JSON.parse(readFileSync(path, 'utf8'));
    if (norm(rec.title) !== norm(pub.title)) {
      errors.push(`${name}: title differs from Crossref.\n    site:     ${pub.title}\n    crossref: ${rec.title}`);
    }
    const recAuthors = rec.authors.map((a) => norm(`${a.given} ${a.family}`)).join(' | ');
    const pubAuthors = pub.authors.map((a) => norm(a.name)).join(' | ');
    if (recAuthors !== pubAuthors) {
      errors.push(`${name}: author list differs from Crossref.\n    site:     ${pubAuthors}\n    crossref: ${recAuthors}`);
    }
  }
}

console.log(`check: ${hits.length} placeholder(s)${allowPlaceholders ? ' (allowed)' : ''}, wrote PLACEHOLDERS.md`);
if (errors.length) {
  console.error('\ncheck failed:\n- ' + errors.join('\n- '));
  process.exit(1);
}
console.log('check: passed');
